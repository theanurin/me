import qrcode
import qrcode.image.svg
import matplotlib.pyplot as plt

# Дані для QR-коду
#url = "https://thebattery.in.ua/p/battery-case-mb31-4s-v1?id=bt3NmWKD" # id:3
#url = "https://thebattery.in.ua/p/battery-case-mb31-4s-v1?id=bt3QFXzb" # id:4
url = "https://thebattery.in.ua/p/battery-case-mb31-4s-v1?id=bt3NmYiF" # id:5
#url = "https://thebattery.in.ua/p/battery-case-mb31-4s-v1?id=bt3QFY2o" # id:6
#url = "https://thebattery.in.ua/p/battery-case-mb31-4s-v1?id=bt3NmYkT" # id:7
#url = "https://thebattery.in.ua/p/battery-case-mb31-4s-v1?id=bt6g1udV" # id:8
#url = "https://thebattery.in.ua/p/battery-case-mb31-4s-v1?id=bt6eXvM9" # id:9

# Відступ
offset_x = 40
# offset_y = 221
offset_y = 5

# factory = qrcode.image.svg.SvgPathImage
# img = qrcode.make(
#     url,
#     error_correction=qrcode.constants.ERROR_CORRECT_H,
#     image_factory=factory,
#     box_size=10, # Масштаб модулів
#     border=4     # Стандартна рамка для правильного читання сканером
# )
# # Зберігаємо готовий SVG файл
# img.save("qrcode-to-dot-pen-gcode.local.svg")
# print("QR-код успішно збережено у форматі SVG!")

# Створення QR-коду з високим рівнем корекції помилок (ERROR_CORRECT_H)
qr = qrcode.QRCode(
    version=None,
    error_correction=qrcode.constants.ERROR_CORRECT_H,
    box_size=1,
    border=4,      # Невеликий відступ (рамка) навколо коду
)
qr.add_data(url)
qr.make(fit=True)

# Отримуємо матрицю пікселів
matrix = qr.get_matrix()

# Параметри обробки для станка (крок 1.08мм для розміру <50x50)
pitch = 1.08

# Координати для збереження точок для прев'ю
x_coords = []
y_coords = []

# Відступи для 4 точок усередині однієї комірки (сітка 2х2)
sub_offsets = [
    (-0.25, -0.25),
    (0.25, -0.25),
    (-0.25, 0.25),
    (0.25, 0.25)
]

# Проходимо по матриці та генеруємо координати
points = []
for row_idx, row in enumerate(matrix):
    y_base = row_idx * pitch
    for col_idx, cell in enumerate(row):
        if cell:  # Якщо тут є точка

            x_base = col_idx * pitch
            for dx, dy in sub_offsets:
                x_pos = x_base + dx
                y_pos = y_base + dy

                x_coords.append(x_pos)
                y_coords.append(y_pos)

                x_offset_pos = x_pos + offset_x
                y_offset_pos = y_pos + offset_y

                points.append([x_offset_pos, y_offset_pos])

            pass

point_total = len(points)

gcode_lines = [
    ";",
    "; THIS FILE WAS GENERATED BY ../../dot-peen-gcode/qrcode-to-dot-pen-gcode.py",
    ";",
    f"; QR Content  : {url}",
    f"; QR Offset X : {offset_x}",
    f"; QR Offset Y : {offset_y}",
    f"; QR Total Points : {point_total}",
    ";",
    "; Tool      : Center Drill 3-4mm",
    ";",
    "#1000 = 2.400     (total drilling depth in Z)",
    "#1001 = 3.100     (reference plane in Z)",
    "#1002 = 3.600     (safe move plane in Z)",
    "#1003 = 20.000    (clearance plane in Z)",
    "#1004 = 30.000    (drilling feed in Z)",
    "G17 G54 G40 G49 G80 G90",
    "G21",
    ";",
    "G0 Z[#1003]",
    "G0 X180",
    "G0 Y213",
    ";",
    "M3 S4000",
    "M0 (!!! override spindle speed override to 66Hz/4000RPM)",
    ";",
]

first_drill_point = True
point_count = 0
for point in points:
    x_offset_pos = point[0]
    y_offset_pos = point[1]

    if first_drill_point:
        gcode_lines.append("G0 Z[#1003]")
        gcode_lines.append(f"G0 X{x_offset_pos:.3f} Y{y_offset_pos:.3f}")
        gcode_lines.append("G0 Z[#1002]")
        gcode_lines.append("G98")
    
    
    if point_count % 4 == 0:
        if not first_drill_point:
            # перезапуск цикла кожні 4 крапок, щоб можна було використати паузу Feed Hold
            gcode_lines.append("G80")
        qr_dot_count = int(point_count / 4)
        qr_dot_total = int(point_total / 4)
        gcode_lines.append(f"(drilling {qr_dot_count}/{qr_dot_total})")
        gcode_lines.append(f"G82 X{x_offset_pos:.3f} Y{y_offset_pos:.3f} Z[#1000] F[#1004] R[#1001] P0.100")
    else:
        gcode_lines.append(f"X{x_offset_pos:.3f} Y{y_offset_pos:.3f}")

    point_count += 1
    first_drill_point = False

    pass

gcode_lines.append("G80")
gcode_lines.append(";")
gcode_lines.append("G0 Z[#1003]")
gcode_lines.append("(goto center)")
gcode_lines.append("G0 X180 Y213")
gcode_lines.append("G0 Y480")
gcode_lines.append("(stopping spindle)")
gcode_lines.append("M05")
gcode_lines.append("G17 G54 G90 G80 G40")
gcode_lines.append("(bye-bye)")
gcode_lines.append("M2")
gcode_lines.append("")

# Зберігаємо G-код у файл
filename_nc = "qrcode-to-dot-pen-gcode.local.nc"
with open(filename_nc, "w", encoding="utf-8") as f:
    f.write("\r\n".join(gcode_lines))

# Генерація зображення (прев'ю) для візуальної перевірки
plt.figure(figsize=(6, 6))
plt.scatter(x_coords, y_coords, s=5, c='black', marker='o')
plt.gca().set_aspect('equal', adjustable='box')
plt.title("Візуальна перевірка масиву точок QR-коду")
plt.xlabel("X (мм)")
plt.ylabel("Y (мм)")
plt.gca().invert_yaxis()  # Інвертуємо вісь Y, щоб відповідати орієнтації ЧПК станків
# plt.grid(True, linestyle='--', alpha=1)

filename_img = "qrcode-to-dot-pen-gcode.local.png"
plt.savefig(filename_img, dpi=300, bbox_inches='tight')
plt.close()

print(f"Готово! Згенеровано G-код: {filename_nc}")
print(f"Згенеровано зображення для перевірки: {filename_img}")