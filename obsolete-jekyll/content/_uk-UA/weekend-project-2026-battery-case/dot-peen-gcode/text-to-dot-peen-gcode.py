import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

font_file = "/Users/maxim.anurin/w-own/me/obsolete-jekyll/content/_uk-UA/weekend-project-2026-battery-case/Roboto/Roboto-VariableFont_wdth,wght.ttf"
text = "thebattery.in.ua"
# Відступ
offset_x = 61
offset_y = 416
# offset_y = 200

scale = 0.5  # 1 pixel = 0.5 mm

# Знаходимо розмір шрифту, що дає висоту літер близько 10 мм.
font_size = 37
font = ImageFont.truetype(font_file, font_size)
# HEIGHT_MM = 60
# while True:
#     bbox = font.getbbox(text)
#     height = bbox[3] - bbox[1]
#     if height <= HEIGHT_MM * SCALE:
#         break
#     font_size -= 1
#     font = ImageFont.truetype(font_file, font_size)

bbox = font.getbbox(text)
left, top, right, bottom = bbox
width = right - left
height = bottom - top

image = Image.new("L", (width, height), 0)
draw = ImageDraw.Draw(image)
draw.text((-left, -top), text, font=font, fill=255)
image = image.rotate(-90, expand=True)
image.save("text-to-dot-peen-gcode.local.png")

# Усі точки, що належать літерам.
pixels = image.load()
points = []
min_x = None

for y in range(width):
    for x in range(height):
        if pixels[x, y] > 0:
            # Інвертуємо вісь Y, щоб відповідати орієнтації ЧПК станків
            inverted_y = height - 1 - y
            # Початок координат — нижній лівий кут.
            points.append([x, height - 1 - y])

with open("text-to-dot-peen-gcode-coordinates.local.json", "w", encoding="utf-8") as f:
    json.dump(points, f, ensure_ascii=False)


gcode_lines = [
    ";",
    "; THIS FILE WAS GENERATED BY ../../dot-peen-gcode/text-to-dot-peen-gcode.py",
    ";",
    f"; Text Content      : {text}",
    f"; Text Offset X     : {offset_x}",
    f"; Text Offset Y     : {offset_y}",
    f"; Text X Distance   : {offset_x} .. {offset_x + height * scale}",
    f"; Text Y Distance   : {offset_y} .. {offset_y - width * scale}",
    f"; Text Total Points : {len(points)}",
    ";",
    "; Safe Z    : 3.5 (12.1)",
    "; Working Z : 3.2 -> #1000",
    "; Tool      : Center Drill 3-4mm",
    ";",
    "#1000 = 2.200     (total drilling in Z)",
    "G17 G54 G40 G49 G80 G90",
    "G21",
    ";",
    "G0 X180",
    "G0 Y213",
    "G0 Z12.1",
    ";",
    "M3 S4000",
    ";",
]


first_drill_point = True
for point in points:
    x_pos = point[0] * scale
    y_pos = point[1] * scale

    x_offset_pos = x_pos + offset_x
    y_offset_pos = y_pos + offset_y - (height * scale)

    if first_drill_point:
        first_drill_point = False
        gcode_lines.append("G0 Z12.1")
        gcode_lines.append(f"G0 X{x_offset_pos:.3f} Y{y_offset_pos:.3f}")
        gcode_lines.append("G0 Z4.000")
        gcode_lines.append("G98")
        gcode_lines.append(f"G82 X{x_offset_pos:.3f} Y{y_offset_pos:.3f} Z[#1000] F30.000 R3.200 P0.100")
    else:
        gcode_lines.append(f"X{x_offset_pos:.3f} Y{y_offset_pos:.3f}")

    pass

gcode_lines.append("G80")
gcode_lines.append("G0 Z12.1")
gcode_lines.append(";")
gcode_lines.append("G0 Z12.1")
gcode_lines.append("(goto center)")
gcode_lines.append("G0 X180 Y213")
gcode_lines.append("G0 Y480")
gcode_lines.append("(stopping spindle)")
gcode_lines.append("M05")
gcode_lines.append("G17 G54 G90 G80 G40")
gcode_lines.append("(bye-bye)")
gcode_lines.append("M2")
gcode_lines.append("")

# Зберігаємо G-код у файл
filename_nc = "text-to-dot-peen-gcode.local.nc"
with open(filename_nc, "w", encoding="utf-8") as f:
    f.write("\r\n".join(gcode_lines))


print(f"Текст: {text}")
print(f"Розмір растра: {width} × {height} мм")
print(f"Кількість точок: {len(points)}")
print("Створено text-mask.png та coordinates.json")
